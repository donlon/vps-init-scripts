#!/bin/bash

set -Eeuo pipefail
trap 'echo "Failed at $BASH_SOURCE:$LINENO: $BASH_COMMAND" >&2' ERR

if [ "$(id -u)" != "0" ]; then
    echo 'Please run this script as root user' >&2
    exit 1
fi

DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
source "$DIR/common.sh"
load_host_config "${1:-$DIR/host.conf}"
source "$DIR/zsh.sh"
cd -- "$DIR"

# Check access before changing passwords, SSH settings, or firewall rules.
if [ ! -r "$DIR/authorized_keys" ] || [ ! -s "$DIR/authorized_keys" ]; then
    echo "Missing or empty $DIR/authorized_keys; supply your SSH public key(s)." >&2
    exit 1
fi
ssh-keygen -lf "$DIR/authorized_keys" >/dev/null
if ! command -v apt-get >/dev/null || ! command -v systemctl >/dev/null; then
    echo 'This script requires an apt-based Linux host running systemd.' >&2
    exit 1
fi


update_user_pwd () {
    local user_name=$1 password
    password=$(openssl rand -hex 24)
    printf '%s:%s\n' "$user_name" "$password" | chpasswd
    printf 'New password for %s is %s\n' "$user_name" "$password"
}

setup_system() {
    OLD_HOSTNAME=$(hostname)
    echo "Change host name to $HOST_NAME"
    hostnamectl set-hostname "$HOST_NAME"

    sed -i "s/$OLD_HOSTNAME/$HOST_NAME/g" /etc/hosts
    # TODO: Generated by SolusVM
    # TODO: force add 127.0.0.1 $HOST_NAME, ::1 $$HOST_NAME
}

setup_users() {
    update_user_pwd root

    USER_NAME=admin
    # TODO: check if admin exists
    echo Setup new user ${USER_NAME}...

    useradd admin &&
        mkdir -p ~admin/.ssh &&
        chown admin:admin ~admin && chmod 700 ~admin &&
        chown admin:admin ~admin/.ssh && chmod 700 ~admin/.ssh &&
        cat ./authorized_keys >> ~admin/.ssh/authorized_keys &&
        chown admin:admin ~admin/.ssh/authorized_keys && chmod 700 ~admin/.ssh/authorized_keys

    # Verify authorized_keys
    [ $(sha256sum ~admin/.ssh/authorized_keys | cut -d' ' -f1) != $(sha256sum ./authorized_keys | cut -d' ' -f1) ] && {
        echo "failed to write authorized_keys"
        exit 1
    }
    update_user_pwd admin
    adduser admin sudo
    sed -i 's/^[#\s]*%sudo\s*ALL.*/%sudo   ALL=(ALL:ALL) NOPASSWD: ALL/' /etc/sudoers
}

update_config() {
    PROP=$1
    VALUE=$2
    FILE=$3
    sed -i "s/^[#\s]*$PROP .*/$PROP $VALUE/" $FILE
}

update_sshd_config() {
    PROP=$1
    VALUE=$2
    update_config $PROP $VALUE /etc/ssh/sshd_config
}

setup_sshd() {
    echo "Update sshd config..."
    update_sshd_config PermitRootLogin no
    update_sshd_config StrictModes yes
    update_sshd_config PubkeyAuthentication yes
    update_sshd_config PasswordAuthentication no
    update_sshd_config PermitEmptyPasswords no
    update_sshd_config ClientAliveInterval 5
    update_sshd_config ClientAliveCountMax 12

    mkdir /etc/ssh/old/
    mv /etc/ssh/ssh_host_* /etc/ssh/old/
    ssh-keygen -A
    # restorecon /etc/ssh/ssh_host_*
    echo "New ssh host keys:"
    cat /etc/ssh/ssh_host_*_key.pub | ssh-keygen -lf -

    echo "Restart sshd..."
}

update_packages() {
    echo Install common packages...
    apt update
    apt upgrade -y
    apt install sudo tmux mtr dnsutils htop rsync zsh git vim curl wget unzip gnupg socat \
        iftop iotop ncdu proxychains python-is-python3 ufw zip unzip xxd strace -y
}

setup_ufw() {
    ufw default deny incoming
    ufw default allow outgoing
    ufw allow ssh
    ufw show added
    ufw --force enable
}

setup_misc() {
    echo 'set number' > /etc/vim/vimrc.local
    sed -i '/^socks4 .*/d' /etc/proxychains.conf
    echo "socks5 127.0.0.1 1080" >> /etc/proxychains.conf
    echo "" >> /etc/proxychains.conf
}

# TODO: prompt hostname

setup_system
setup_users
setup_sshd
# add prompt before install packages
update_packages
setup_zsh
chsh -s /usr/bin/zsh

setup_ufw
setup_misc

ADMIN_SETUP_DIR=$(mktemp -d /home/admin/.vps-init.XXXXXX)
install -o admin -g admin -m 600 "$CONFIG_FILE" "$ADMIN_SETUP_DIR/host.conf"
install -o admin -g admin -m 644 admin.sh common.sh zsh.sh "$ADMIN_SETUP_DIR/"
chown admin:admin "$ADMIN_SETUP_DIR"
su - admin -c "bash '$ADMIN_SETUP_DIR/admin.sh' '$ADMIN_SETUP_DIR/host.conf'"
rm -- "$ADMIN_SETUP_DIR/admin.sh" "$ADMIN_SETUP_DIR/common.sh" "$ADMIN_SETUP_DIR/zsh.sh" "$ADMIN_SETUP_DIR/host.conf"
rmdir -- "$ADMIN_SETUP_DIR"
chsh -s /usr/bin/zsh admin
