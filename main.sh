setup_zsh() {
    echo Setup zsh...
    # su admin -c '
    sh -c "$(wget -O- https://raw.githubusercontent.com/ohmyzsh/ohmyzsh/master/tools/install.sh)"
    # TODO: exit zsh after install

    git clone --depth=1 https://github.com/zsh-users/zsh-autosuggestions.git \
        ${ZSH_CUSTOM:-$HOME/.oh-my-zsh/custom}/plugins/zsh-autosuggestions
    # git clone --depth=1 https://github.com/zsh-users/zsh-syntax-highlighting.git \
    #     ${ZSH_CUSTOM:-$HOME/.oh-my-zsh/custom}/plugins/zsh-syntax-highlighting
    git clone --depth=1 https://github.com/z-shell/F-Sy-H.git \
        ${ZSH_nCUSTOM:-$HOME/.oh-my-zsh/custom}/plugins/F-Sy-H

    sed -i '/^plugins=/a\
\
# Max history size\
HISTSIZE=10000000\
HISTFILESIZE=10000000\
\
# .zshcompdump path\
ZSH_COMPDUMP="${XDG_CACHE_HOME:-$HOME/.cache}/.zcompdump-${ZSH_VERSION}"\
autoload -Uz compinit\
compinit -C -d "$ZSH_COMPDUMP"' ~/.zshrc

    sed -i 's/^plugins=.*/plugins=(git zsh-autosuggestions F-Sy-H)/' ~/.zshrc
    sed -i 's/^ZSH_THEME=.*/ZSH_THEME="maran"/' ~/.zshrc

    echo '\
export PATH=$HOME/.local/bin:$HOME/.cargo/bin:/sbin:$PATH\
export EDITOR=vim\
\
alias diff="diff --color=always"\
alias t=tree -a\
alias pxy=proxychains\
' >> $HOME/.zshrc
}

update_user_pwd () {
    USER_NAME=$1
    RAND_PASSWD=$(openssl rand -base64 24)
    RAND_PASSWD="${RAND_PASSWD//[\/+=]/}"
    echo "New password for $USER_NAME is $RAND_PASSWD"
    echo $RAND_PASSWD | passwd -s "$USER_NAME"
    return $?
}

setup_system() {
    OLD_HOSTNAME=$(hostname)
    echo "Change host name to $HOST_NAME"
    hostnamectl set-hostname "$HOST_NAME"

    sed -i "s/$OLD_HOSTNAME/$HOST_NAME/g" /etc/hosts
    # TODO: Generated by SolusVM
    # TODO: force add 127.0.0.1 $HOST_NAME, ::1 $$HOST_NAME
}

setup_users() {
    update_user_pwd root

    USER_NAME=admin
    # TODO: check if admin exists
    echo Setup new user ${USER_NAME}...

    useradd admin &&
        mkdir -p ~admin/.ssh &&
        chown admin:admin ~admin && chmod 700 ~admin &&
        chown admin:admin ~admin/.ssh && chmod 700 ~admin/.ssh &&
        cat ./authorized_keys >> ~admin/.ssh/authorized_keys &&
        chown admin:admin ~admin/.ssh/authorized_keys && chmod 700 ~admin/.ssh/authorized_keys

    # Verify authorized_keys
    [ $(sha256sum ~admin/.ssh/authorized_keys | cut -d' ' -f1) != $(sha256sum ./authorized_keys | cut -d' ' -f1) ] && {
        echo "failed to write authorized_keys"
        exit 1
    }
    update_user_pwd admin
    adduser admin sudo
    sed -i 's/^[#\s]*%sudo\s*ALL.*/%sudo   ALL=(ALL:ALL) NOPASSWD: ALL/' /etc/sudoers
}

update_config() {
    PROP=$1
    VALUE=$2
    FILE=$3
    sed -i "s/^[#\s]*$PROP .*/$PROP $VALUE/" $FILE
}

update_sshd_config() {
    PROP=$1
    VALUE=$2
    update_config $PROP $VALUE /etc/ssh/sshd_config
}

setup_sshd() {
    echo "Update sshd config..."
    update_sshd_config PermitRootLogin no
    update_sshd_config StrictModes yes
    update_sshd_config PubkeyAuthentication yes
    update_sshd_config PasswordAuthentication no
    update_sshd_config PermitEmptyPasswords no
    update_sshd_config ClientAliveInterval 5
    update_sshd_config ClientAliveCountMax 12

    mkdir /etc/ssh/old/
    mv /etc/ssh/ssh_host_* /etc/ssh/old/
    ssh-keygen -A
    # restorecon /etc/ssh/ssh_host_*
    echo "New ssh host keys:"
    cat /etc/ssh/ssh_host_*_key.pub | ssh-keygen -lf -

    echo "Restart sshd..."
}

update_packages() {
    echo Install common packages...
    apt update
    apt upgrade -y
    apt install sudo tmux mtr dnsutils htop rsync zsh git vim curl wget unzip gnupg socat \
        iftop iotop ncdu proxychains python-is-python3 ufw zip unzip xxd strace -y
}

setup_ufw() {
    ufw default deny incoming
    ufw default allow outgoing
    ufw allow ssh
    ufw show added
    ufw --force enable
}

setup_misc() {
    echo 'set number' > /etc/vim/vimrc.local
    sed -i '/^socks4 .*/d' /etc/proxychains.conf
    echo "socks5 127.0.0.1 1080" >> /etc/proxychains.conf
    echo "" >> /etc/proxychains.conf
}

